const last = new Map();
/** Frase al azar sin repetir la anterior. */
export function pick(who, kind = null) {
  const pool = kind ? LINES[who]?.[kind] : LINES[who];
  if (!pool?.length) return '';
  const key = who + '|' + (kind || '');
  let i = Math.floor(Math.random() * pool.length);
  if (pool.length > 1 && i === last.get(key)) i = (i + 1) % pool.length;
  last.set(key, i);
  return pool[i];
}
/** Número de frases de un personaje (las de Sebas van por situaciones). */
export function count(who) {
  const L = LINES[who];
  return Array.isArray(L) ? L.length : Object.values(L || {}).reduce((n, a) => n + a.length, 0);
}
